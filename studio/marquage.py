"""Marquage des rendus du studio (module s3d04) : toujours invisible, visible en option.

Appelé par le worker (travailleur.py) juste après Blender, avant de ranger les fichiers : le code
de la scène, écrit par le modèle, ne peut ni l'éviter ni le modifier.
  - invisible, toujours : paquet XMP (type de source IPTC « créé par IA générative », date,
    générateur, identifiant de la demande) et champs texte dans le PNG ; champ `asset` du GLB ;
  - visible, en option : un bandeau toujours identique, en bas à droite (source et date).
Module s3d05 : la trace des assets de la bibliothèque utilisés (nom, source, licence) rejoint le marquage.
"""
import json
import struct
import time
import uuid
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont
from PIL.PngImagePlugin import PngInfo

GENERATEUR = "AI studio3D"
# Vocabulaire IPTC « Digital Source Type » : créé par un modèle entraîné (IA générative).
TYPE_SOURCE = "http://cv.iptc.org/newscodes/digitalsourcetype/trainedAlgorithmicMedia"
# Police du paquet Debian fonts-dejavu-core : même rendu partout.
POLICE = "/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf"


def infos(demande: dict, fin: float, assets: list | None = None, bibliotheque=None) -> dict:
    """Ce que porte la marque : identifiant de la demande, date de fin du rendu (UTC), assets utilisés."""
    t = time.gmtime(fin)
    identifiant = demande.get("identifiant") or str(uuid.uuid4())  # demande antérieure au module 4
    return {"identifiant": identifiant, "numero": demande.get("numero", ""),
            "date": time.strftime("%Y-%m-%dT%H:%M:%SZ", t),
            "jour": time.strftime("%Y-%m-%d", t),
            "rfc1123": time.strftime("%a, %d %b %Y %H:%M:%S GMT", t),
            "assets": assets or [], "bibliotheque": bibliotheque}


# ---------------------------------------------------------------- Invisible : métadonnées

def xmp(i: dict) -> str:
    """Paquet XMP : le format de métadonnées que lisent les logiciels d'image."""
    return f"""<?xpacket begin="﻿" id="W5M0MpCehiHzreSzNTczkc9d"?>
<x:xmpmeta xmlns:x="adobe:ns:meta/">
 <rdf:RDF xmlns:rdf="http://www.w3.org/1999/02/22-rdf-syntax-ns#">
  <rdf:Description rdf:about=""
    xmlns:Iptc4xmpExt="http://iptc.org/std/Iptc4xmpExt/2008-02-29/"
    xmlns:xmp="http://ns.adobe.com/xap/1.0/"
    xmlns:xmpMM="http://ns.adobe.com/xap/1.0/mm/"
    Iptc4xmpExt:DigitalSourceType="{TYPE_SOURCE}"
    xmp:CreatorTool="{GENERATEUR}"
    xmp:CreateDate="{i['date']}"
    xmpMM:DocumentID="urn:uuid:{i['identifiant']}"/>
 </rdf:RDF>
</x:xmpmeta>
<?xpacket end="r"?>"""


def marquer_png(chemin: Path, i: dict, visible: bool) -> None:
    image = Image.open(chemin)
    image.load()
    if visible:
        image = bandeau(image, i["jour"])
    # Champs texte du PNG, pour les outils simples (lus par des machines : en anglais).
    meta = PngInfo()
    meta.add_text("Software", GENERATEUR)
    meta.add_text("Creation Time", i["rfc1123"])
    meta.add_text("Source", f"{GENERATEUR} (Blender 5.2)")
    meta.add_text("Disclaimer", "Generated by AI")
    if i.get("assets"):  # assets de la bibliothèque utilisés (module s3d05)
        meta.add_text("Assets", ", ".join(f"{a['nom']} ({a['source']}, {a['licence']})" for a in i["assets"]))
    # Le paquet XMP, sous son mot-clé standard dans un PNG.
    meta.add_itxt("XML:com.adobe.xmp", xmp(i))
    # Réenregistré par Pillow : les métadonnées de Blender sont remplacées.
    image.save(chemin, pnginfo=meta)


# ---------------------------------------------------------------- Visible : le bandeau

def bandeau(image: Image.Image, jour: str) -> Image.Image:
    """Toujours identique : même police, même taille, même place.
    Seule la date change."""
    texte = f"{GENERATEUR} · {jour}"
    police = ImageFont.truetype(POLICE, 22)
    calque = Image.new("RGBA", image.size, (0, 0, 0, 0))
    d = ImageDraw.Draw(calque)
    gauche, haut, droite, bas = d.textbbox((0, 0), texte, font=police)
    # En bas à droite : marge de 16 px, marges intérieures de 10 et 8 px.
    x1, y1 = image.width - 16, image.height - 16
    x0, y0 = x1 - (droite - gauche) - 20, y1 - (bas - haut) - 16
    d.rectangle((x0, y0, x1, y1), fill=(0, 0, 0, 153))  # noir à 60 %
    d.text((x0 + 10 - gauche, y0 + 8 - haut), texte, font=police, fill="white")
    return Image.alpha_composite(image.convert("RGBA"), calque).convert("RGB")


# ---------------------------------------------------------------- Modèle 3D : le GLB

def marquer_glb(chemin: Path, i: dict) -> None:
    """Un GLB : un en-tête de 12 octets, puis un bloc JSON, où l'on réécrit `asset`."""
    data = chemin.read_bytes()
    longueur, genre = struct.unpack_from("<I4s", data, 12)  # premier bloc
    if data[:4] != b"glTF" or genre != b"JSON":
        raise ValueError("fichier GLB inattendu")
    doc = json.loads(data[20:20 + longueur])
    asset = doc.setdefault("asset", {})
    asset["extras"] = {
        **asset.get("extras", {}),
        "digitalSourceType": TYPE_SOURCE,
        "createDate": i["date"],
        "identifiant": f"urn:uuid:{i['identifiant']}",
        "exportePar": asset.get("generator", ""),
    }
    if i.get("assets"):  # la trace des assets : nom, source, licence (module s3d05)
        asset["extras"]["assets"] = i["assets"]
        asset["extras"]["bibliotheque"] = i["bibliotheque"]
    asset["generator"] = GENERATEUR
    js = json.dumps(doc, ensure_ascii=False, separators=(",", ":")).encode()
    js += b" " * (-len(js) % 4)       # alignement sur quatre octets
    reste = data[20 + longueur:]      # bloc binaire, inchangé
    total = 20 + len(js) + len(reste)  # longueurs recalculées
    chemin.write_bytes(struct.pack("<4sII", b"glTF", 2, total)
                       + struct.pack("<I4s", len(js), b"JSON") + js + reste)
